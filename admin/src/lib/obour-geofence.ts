/** Ray casting — ring is [lng, lat][]. */
export function pointInRing(
  longitude: number,
  latitude: number,
  ring: readonly LngLat[],
): boolean {
  if (ring.length < 4) {
    return false;
  }

  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]!;
    const [xj, yj] = ring[j]!;
    const intersect =
      yi > latitude !== yj > latitude &&
      longitude < ((xj - xi) * (latitude - yi)) / (yj - yi + Number.EPSILON) + xi;
    if (intersect) {
      inside = !inside;
    }
  }
  return inside;
}

/** Absolute shoelace area (degrees²) — for picking smallest overlap. */
export function ringArea(ring: readonly LngLat[]): number {
  let sum = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const [x1, y1] = ring[i]!;
    const [x2, y2] = ring[i + 1]!;
    sum += x1 * y2 - x2 * y1;
  }
  return Math.abs(sum) / 2;
}

export type ObourDetectResult =
  | { status: "district"; districtName: string }
  | { status: "city_only" }
  | { status: "outside_city" };

/**
 * 1) خارج العبور → outside_city
 * 2) جوه حي → district (أصغر مضلع عند التداخل)
 * 3) جوه العبور بدون حي → city_only
 */
export function detectObourDistrict(
  latitude: number,
  longitude: number,
): ObourDetectResult {
  if (!pointInRing(longitude, latitude, OBOUR_CITY_RING)) {
    return { status: "outside_city" };
  }

  let best: ObourDistrictPolygon | null = null;
  let bestArea = Number.POSITIVE_INFINITY;

  for (const polygon of OBOUR_DISTRICT_POLYGONS) {
    if (!pointInRing(longitude, latitude, polygon.ring)) {
      continue;
    }
    const area = ringArea(polygon.ring);
    if (area < bestArea) {
      bestArea = area;
      best = polygon;
    }
  }

  if (best) {
    return { status: "district", districtName: best.name };
  }

  return { status: "city_only" };
}
